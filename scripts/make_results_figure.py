#!/usr/bin/env python3
"""Turn one four-configuration paired campaign into pgfplots data tables.

Reads data/paired/<label>/summary.tsv and writes two tables under
paper/figures/. The level table <name>.dat holds, per offered load and
configuration, the median and the min-max range of the processed rate. The
difference table <name>_diff.dat holds, per offered load and hook, the median
and min-max range of the within-block difference read-data minus no-touch, for
cycles and for DRAM fills per packet. The scatter table <name>_scatter.dat holds
one row per block at the native hook, with both differences and the offered
load, and the fit of cycles on fills is printed for the caption. The difference
is formed inside a block, so load, machine state, and configuration order are
held fixed.

Only valid instrumented cells are used, the same set the analysis report
aggregates.

Usage:
    scripts/make_results_figure.py data/paired/<label>/summary.tsv thr4_ring512
"""

import csv
import os
import statistics as st
import sys
from collections import defaultdict

CONFIGS = [("native", "no-touch"), ("native", "read-data"),
           ("skb", "no-touch"), ("skb", "read-data")]
KEYS = ["nnt", "nrd", "gnt", "grd"]
LOSS_THRESHOLD = 0.001
# Per-packet columns carried into the level and difference tables, in order.
COST = [("cycles_per_pkt", "cyc"), ("dram_fills_per_pkt", "dram"),
        ("l2_fills_per_pkt", "l2"), ("ccx_fills_per_pkt", "ccx")]
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def write_differences(cost, rates, out, summary):
    """Per load and hook, the block differences read-data minus no-touch."""
    blocks = sorted({k[3] for k in cost})
    header = ["offered"]
    for _, metric in COST:
        for hook in ("n", "g"):
            header += [f"{hook}{metric}", f"{hook}{metric}lo", f"{hook}{metric}hi"]

    signs = defaultdict(lambda: [0, 0])
    with open(out, "w") as f:
        f.write("% generated by scripts/make_results_figure.py from "
                f"{os.path.basename(os.path.dirname(summary))}\n")
        f.write(" ".join(header) + "\n")
        for rate in rates:
            cols = [f"{rate/1e6:.5f}"]
            for index in range(len(COST)):
                for mode in ("native", "skb"):
                    diffs = [cost[(mode, "read-data", rate, b)][index]
                             - cost[(mode, "no-touch", rate, b)][index]
                             for b in blocks]
                    cols += [f"{st.median(diffs):.4f}",
                             f"{min(diffs):.4f}", f"{max(diffs):.4f}"]
                    tally = signs[(mode, index)]
                    tally[0] += sum(1 for d in diffs if d > 0)
                    tally[1] += len(diffs)
            f.write(" ".join(cols) + "\n")

    for (mode, index), (positive, total) in sorted(signs.items()):
        metric = COST[index][1]
        alldiffs = [cost[(mode, "read-data", r, b)][index]
                    - cost[(mode, "no-touch", r, b)][index]
                    for r in rates for b in blocks]
        print(f"{mode:7}{metric:6} median difference {st.median(alldiffs):+9.4f}, "
              f"positive in {positive}/{total} pairs")
    print(f"wrote {out}")


def correlate(xs, ys):
    """Pearson r and the least-squares line y = a + b x."""
    mx, my = st.mean(xs), st.mean(ys)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    slope = sxy / sxx
    return sxy / (sxx * syy) ** 0.5, slope, my - slope * mx


def write_scatter(cost, rates, out, summary):
    """One row per block at the native hook, both differences and the load."""
    blocks = sorted({k[3] for k in cost})
    fills, cycles, within = [], [], [[], []]
    with open(out, "w") as f:
        f.write("% generated by scripts/make_results_figure.py from "
                f"{os.path.basename(os.path.dirname(summary))}\n")
        f.write("dram cyc load\n")
        for rate in rates:
            here = [(cost[("native", "read-data", rate, b)][1]
                     - cost[("native", "no-touch", rate, b)][1],
                     cost[("native", "read-data", rate, b)][0]
                     - cost[("native", "no-touch", rate, b)][0]) for b in blocks]
            mean_f = st.mean(d for d, _ in here)
            mean_c = st.mean(c for _, c in here)
            for d, c in here:
                f.write(f"{d:.4f} {c:.3f} {rate/1e6:.4f}\n")
                fills.append(d)
                cycles.append(c)
                within[0].append(d - mean_f)
                within[1].append(c - mean_c)

    r, slope, intercept = correlate(fills, cycles)
    r_within = correlate(within[0], within[1])[0]
    origin = sum(d * c for d, c in zip(fills, cycles)) / sum(d * d for d in fills)
    print(f"native  scatter    n={len(fills)} r={r:.3f} (within load {r_within:.3f}), "
          f"fit cycles = {intercept:.1f} + {slope:.1f} x fills, "
          f"through origin {origin:.1f}")
    print(f"wrote {out}")


def write_levels(cost, rates, out, summary):
    """Per load and configuration, the level of each per-packet cost column."""
    blocks = sorted({k[3] for k in cost})
    header = ["offered"]
    for _, metric in COST:
        for key in KEYS:
            header += [f"{key}_{metric}", f"{key}lo_{metric}", f"{key}hi_{metric}"]
    with open(out, "w") as f:
        f.write("% generated by scripts/make_results_figure.py from "
                f"{os.path.basename(os.path.dirname(summary))}\n")
        f.write(" ".join(header) + "\n")
        for rate in rates:
            cols = [f"{rate/1e6:.5f}"]
            for index in range(len(COST)):
                for config in CONFIGS:
                    vals = [cost[(config[0], config[1], rate, b)][index]
                            for b in blocks]
                    cols += [f"{st.median(vals):.4f}",
                             f"{min(vals):.4f}", f"{max(vals):.4f}"]
            f.write(" ".join(cols) + "\n")
    print(f"wrote {out}")


def main():
    summary, name = sys.argv[1:3]
    accepted = defaultdict(list)
    loss = defaultdict(list)
    cost = {}
    with open(summary, newline="") as stream:
        for row in csv.DictReader(stream, delimiter="\t"):
            if row["valid"] != "True" or row["instrumented"] != "1":
                continue
            key = (row["mode"], row["variant"], int(row["rate"]))
            accepted[key].append(float(row["accepted_pps"]))
            loss[key].append(float(row["loss"]))
            cost[key + (int(row["block"]),)] = tuple(
                float(row[column]) for column, _ in COST)

    rates = sorted({k[2] for k in accepted})
    header = ["offered"]
    for k in KEYS:
        header += [f"{k}", f"{k}lo", f"{k}hi"]

    out = os.path.join(REPO, "paper", "figures", f"{name}.dat")
    with open(out, "w") as f:
        f.write("% generated by scripts/make_results_figure.py from "
                f"{os.path.basename(os.path.dirname(summary))}\n")
        f.write(" ".join(header) + "\n")
        for rate in rates:
            cols = [f"{rate/1e6:.5f}"]
            for config in CONFIGS:
                vals = accepted[(config[0], config[1], rate)]
                cols += [f"{st.median(vals)/1e6:.5f}",
                         f"{min(vals)/1e6:.5f}", f"{max(vals)/1e6:.5f}"]
            f.write(" ".join(cols) + "\n")

    write_differences(cost, rates, os.path.join(REPO, "paper", "figures",
                                                f"{name}_diff.dat"), summary)
    write_scatter(cost, rates, os.path.join(REPO, "paper", "figures",
                                            f"{name}_scatter.dat"), summary)
    write_levels(cost, rates, os.path.join(REPO, "paper", "figures",
                                           f"{name}_cost.dat"), summary)

    for config in CONFIGS:
        clean = [r for r in rates
                 if st.median(loss[(config[0], config[1], r)]) <= LOSS_THRESHOLD]
        limited = [r for r in rates
                   if st.median(loss[(config[0], config[1], r)]) > LOSS_THRESHOLD]
        clean_text = (f"below loss threshold through {max(clean)/1e6:7.3f} Mpps"
                      if clean else "no load below loss threshold")
        if limited:
            plateau = [value for rate in limited
                       for value in accepted[(config[0], config[1], rate)]]
            print(f"{config[0]:7}{config[1]:11} {clean_text}, "
                  f"plateau {st.mean(plateau)/1e6:6.3f} Mpps over "
                  f"{len(limited)} loads and {len(plateau)} blocks")
        else:
            top = accepted[(config[0], config[1], rates[-1])]
            print(f"{config[0]:7}{config[1]:11} {clean_text}, "
                  f"capacity at least {st.median(top)/1e6:6.3f} Mpps")
    print(f"wrote {out} ({len(rates)} rates)")


if __name__ == "__main__":
    main()
